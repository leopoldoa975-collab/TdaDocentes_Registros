    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
      if (contador < listaDocentes.length) {
            String nombre = txtNombre.getText().trim();
            String especialidad = txtEspecialidad.getText().trim();
            String clave = txtClave.getText().trim();

            if (nombre.isEmpty() || especialidad.isEmpty() || clave.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor llena todos los campos.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Instancia del TDA Docente
            Docente docente = new Docente(nombre, especialidad, clave);

            // Almacenar en el arreglo
            listaDocentes[contador] = docente;
            contador++;

            // Mostrar el registro en el JTextArea
            actualizarAreaTexto();

            // Limpiar cajas de texto
            limpiarCampos();
            JOptionPane.showMessageDialog(this, "Docente registrado con éxito.");
        } else {
            JOptionPane.showMessageDialog(this, "El arreglo está lleno. No se pueden agregar más docentes.", "Límite alcanzado", JOptionPane.ERROR_MESSAGE);
        }
}

// Método auxiliar para refrescar el JTextArea
private void actualizarAreaTexto() {
    txtArea.setText("");
    for (int i = 0; i < contador; i++) {
        txtArea.append("--- Docente " + (i + 1) + " ---\n");
        txtArea.append(listaDocentes[i].mostrarDatos() + "\n\n");
    } 
    }//GEN-LAST:event_btnRegistrarActionPerformed

